import { randomUUID } from 'node:crypto';
import { beforeAll, expect, it } from 'vitest';
import { buildApp } from '../../app.js';
import { db, sqlClient } from '../../db/client.js';
import { migrate } from '../../db/migrate.js';
import { AuthService } from '../auth/service.js';
import { AccessService } from '../access/service.js';
beforeAll(() => migrate());
it('replays a committed mutation without duplicating a task, rejects mismatches and enforces current access', async () => {
  const auth = new AuthService(db, { sendRegistrationCode: async () => {}, sendVerification: async () => {}, sendPasswordReset: async () => {} }, { accessSecret: 'mutation-test', emailVerificationRequired: false });
  const email = `${randomUUID()}@example.com`;
  const user = await auth.register(email, 'test-password', 'Tester');
  const access = new AccessService(db);
  const org = await access.createOrganization(user.id, 'Mutations');
  const app = await buildApp({ authService: auth });
  try {
    const team = await access.createTeam(user.id, org.id, 'Core');
    const project = await access.createProject(user.id, team.id, 'Project');
    const token = (await auth.login(email, 'test-password')).accessToken;
    const headers = { authorization: `Bearer ${token}`, 'x-mutation-id': randomUUID() };
    const payload = { title: 'Once', type: 'feature', status: 'backlog', priority: 'P2', estimate: 1 };
    const send = (body = payload) => app.inject({ method: 'POST', url: `/projects/${project.id}/work-items`, headers, payload: body });
    const forged = await app.inject({ method: 'POST', url: `/projects/${project.id}/work-items`, headers: { ...headers, 'x-mutation-id': randomUUID() }, payload: { ...payload, title: 'Forged hours', actualHours: 99 } });
    expect(forged.statusCode).toBe(201);
    expect(forged.json().actualHours).toBeNull();
    const [a, b] = await Promise.all([send(), send()]);
    expect(a.statusCode).toBe(201);
    expect(b.json()).toEqual(a.json());
    expect((await send({ ...payload, title: 'Different' })).statusCode).toBe(409);
    const events = await app.inject({ method: 'GET', url: `/work-items/${a.json().id}/events`, headers });
    expect(events.json()).toHaveLength(1);
    const update = await app.inject({ method: 'PATCH', url: `/work-items/${a.json().id}`, headers: { ...headers, 'x-mutation-id': randomUUID() }, payload: { version: 1, status: 'ready' } });
    const forgedUpdate = await app.inject({ method: 'PATCH', url: `/work-items/${a.json().id}`, headers: { ...headers, 'x-mutation-id': randomUUID() }, payload: { version: update.json().version, actualHours: 99 } });
    expect(forgedUpdate.statusCode).toBe(200);
    expect(forgedUpdate.json().actualHours).toBeNull();
    const start = await app.inject({ method: 'PATCH', url: `/work-items/${a.json().id}`, headers: { ...headers, 'x-mutation-id': randomUUID() }, payload: { version: forgedUpdate.json().version, status: 'in_progress' } });
    const reportHeaders = { ...headers, 'x-mutation-id': randomUUID() };
    const reportBody = { version: start.json().version, summary: 'Done', tests: [{ command: 'test', result: 'passed', outcome: 'passed', exitCode: 0 }] };
    const report = () => app.inject({ method: 'POST', url: `/work-items/${a.json().id}/report`, headers: reportHeaders, payload: reportBody });
    const firstReport = await report();
    expect(firstReport.statusCode).toBe(200);
    expect((await report()).json()).toEqual(firstReport.json());
    const contributions = await app.inject({ method: 'GET', url: `/projects/${project.id}/contributors`, headers });
    expect(contributions.json().members).toMatchObject([{ userId: user.id, reportCount: 1, testCount: 1 }]);
    const acceptanceHeaders = { ...headers, 'x-mutation-id': randomUUID() };
    const accept = () => app.inject({ method: 'POST', url: `/work-items/${a.json().id}/accept`, headers: acceptanceHeaders, payload: { version: firstReport.json().version, decision: 'approved' } });
    const approved = await accept();
    expect(approved.statusCode).toBe(200);
    expect((await accept()).json()).toEqual(approved.json());
    const logHeaders = { ...headers, 'x-mutation-id': randomUUID() };
    const record = () => app.inject({ method: 'POST', url: `/work-items/${a.json().id}/work-logs`, headers: logHeaders, payload: { hours: 2, content: 'Worked', workDate: '2026-10-05' } });
    const log = await record();
    expect(log.statusCode).toBe(201);
    expect((await record()).json()).toEqual(log.json());
    const current = await app.inject({ method: 'GET', url: `/work-items/${a.json().id}`, headers });
    expect(current.json().actualHours).toBe('2.00');
    const deleteHeaders = { ...headers, 'x-mutation-id': randomUUID() };
    const remove = () => app.inject({ method: 'DELETE', url: `/work-items/${a.json().id}`, headers: deleteHeaders, payload: { version: current.json().version } });
    const deleted = await remove();
    expect(deleted.statusCode).toBe(200);
    expect((await remove()).json()).toEqual(deleted.json());
    await sqlClient`delete from organization_memberships where organization_id=${org.id} and user_id=${user.id}`;
    expect((await send()).statusCode).toBe(404);
  } finally { await app.close(); await sqlClient`delete from organizations where id=${org.id}`; await sqlClient`delete from users where id=${user.id}`; }
});
